//! Bounded, issuer-pinned K-6 signed gateway tickets.

use std::{collections::BTreeMap, fmt};

use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use scoplen_model::validate_uuid_v7;
use serde_json::{Value, json};
use sha2::{Digest as _, Sha256};
use thiserror::Error;
use uuid::Uuid;

use crate::{Ed25519SigningKey, device_auth::validate_origin, dpop, ed25519_verify};

/// Maximum compact JWS length, including the two separators.
pub const MAX_GATEWAY_TICKET_BYTES: usize = 4_096;
/// Exact lifetime of one signed gateway ticket in seconds.
pub const GATEWAY_TICKET_LIFETIME_SECONDS: u64 = 60;
const MAX_KID_BYTES: usize = 128;

/// A gateway ticket or its trusted issuance context is invalid.
#[derive(Clone, Debug, Eq, Error, PartialEq)]
pub enum GatewayTicketError {
    /// Issuer, key identifier, key, or claims supplied for issuance are invalid.
    #[error("invalid gateway ticket signing context")]
    InvalidContext,
    /// The bounded compact JWS, signature, or claims failed verification.
    #[error("invalid gateway ticket")]
    InvalidTicket,
    /// The selected signer failed or returned a signature from a different key.
    #[error("gateway ticket signer failed")]
    SignerFailed,
}

/// A fallible Ed25519 ticket signer, implemented by software or a KMS adapter.
pub trait GatewayTicketSigner {
    /// Sign the exact compact-JWS header and payload segments, including their separator.
    ///
    /// # Errors
    ///
    /// Return `SignerFailed` when the key cannot sign; no partial ticket is issued.
    fn sign(&self, message: &[u8]) -> Result<[u8; 64], GatewayTicketError>;
}

impl GatewayTicketSigner for Ed25519SigningKey {
    fn sign(&self, message: &[u8]) -> Result<[u8; 64], GatewayTicketError> {
        Ok(Ed25519SigningKey::sign(self, message))
    }
}

/// Required signed claims. Issuers must provide a fresh `jti` for every issuance.
#[derive(Clone, Eq, PartialEq)]
pub struct GatewayTicketClaims {
    pub iss: String,
    pub jti: Uuid,
    pub sub: Uuid,
    pub did: Uuid,
    pub org: Uuid,
    pub host: Uuid,
    pub gateway_network: Uuid,
    pub remote_user: String,
    pub ssh_key_sha256: String,
    pub cnf_jkt: String,
    pub iat: u64,
    pub exp: u64,
}

impl fmt::Debug for GatewayTicketClaims {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("GatewayTicketClaims([REDACTED])")
    }
}

impl GatewayTicketClaims {
    /// Validate every required claim before issuance or after signature verification.
    ///
    /// # Errors
    ///
    /// Rejects invalid origins, identifiers, usernames, hashes, or lifetime.
    pub fn validate(&self) -> Result<(), GatewayTicketError> {
        if validate_origin(&self.iss).is_err()
            || [self.jti, self.sub, self.did, self.org, self.host, self.gateway_network]
                .into_iter()
                .any(|id| validate_uuid_v7(id).is_err())
            || self.remote_user.is_empty()
            || self.remote_user.len() > 255
            || self.remote_user.chars().any(char::is_control)
            || fixed_hash(&self.ssh_key_sha256).is_err()
            || fixed_hash(&self.cnf_jkt).is_err()
            || self.iat.checked_add(GATEWAY_TICKET_LIFETIME_SECONDS) != Some(self.exp)
        {
            return Err(GatewayTicketError::InvalidContext);
        }
        Ok(())
    }
}

/// An exact bounded compact JWS. Parsing alone does not establish trust or single use.
#[derive(Clone, Eq, PartialEq)]
pub struct GatewayTicket(String);

impl fmt::Debug for GatewayTicket {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("GatewayTicket([REDACTED])")
    }
}

impl GatewayTicket {
    /// Parse a canonical bounded compact-JWS envelope without trusting its contents.
    ///
    /// # Errors
    ///
    /// Rejects non-ASCII, malformed, padded, oversized, or noncanonical segments and signatures.
    pub fn parse(value: &str) -> Result<Self, GatewayTicketError> {
        let (header, payload, signature) = split_compact(value)?;
        let _ = decode_segment(header)?;
        let _ = decode_segment(payload)?;
        if decode_segment(signature)?.len() != 64 {
            return Err(GatewayTicketError::InvalidTicket);
        }
        Ok(Self(value.to_owned()))
    }

    /// Sign validated claims with a dedicated ticket key and check the signer's output.
    ///
    /// `jti` must be newly generated by the issuer for each call. The public key is the selected
    /// ticket-signing key, never a key from a token, SSH CA, or untrusted request.
    ///
    /// # Errors
    ///
    /// Rejects invalid claims or key identifiers, oversized output, and failed/mismatched signing.
    pub fn sign(
        signer: &(impl GatewayTicketSigner + ?Sized),
        public_key: &[u8],
        kid: &str,
        claims: &GatewayTicketClaims,
    ) -> Result<Self, GatewayTicketError> {
        claims.validate()?;
        if !valid_kid(kid) || public_key.len() != 32 {
            return Err(GatewayTicketError::InvalidContext);
        }
        let header = json!({"alg":"Ed25519", "kid":kid, "typ":"spl-gw-ticket+jwt"});
        let payload = json!({
            "aud":"spl-gw/1", "cnf":{"jkt":claims.cnf_jkt}, "did":claims.did.to_string(),
            "exp":claims.exp, "gateway_network":claims.gateway_network.to_string(),
            "host":claims.host.to_string(), "iat":claims.iat, "iss":claims.iss,
            "jti":claims.jti.to_string(), "org":claims.org.to_string(),
            "remote_user":claims.remote_user, "ssh_key_sha256":claims.ssh_key_sha256,
            "sub":claims.sub.to_string()
        });
        let header = serde_json::to_vec(&header).map_err(|_| GatewayTicketError::InvalidContext)?;
        let payload =
            serde_json::to_vec(&payload).map_err(|_| GatewayTicketError::InvalidContext)?;
        let input =
            format!("{}.{}", URL_SAFE_NO_PAD.encode(header), URL_SAFE_NO_PAD.encode(payload));
        // A 64-byte signature encodes to 86 base64url bytes, plus the final separator.
        if input.len() + 87 > MAX_GATEWAY_TICKET_BYTES {
            return Err(GatewayTicketError::InvalidContext);
        }
        let signature =
            signer.sign(input.as_bytes()).map_err(|_| GatewayTicketError::SignerFailed)?;
        ed25519_verify(public_key, input.as_bytes(), &signature)
            .map_err(|_| GatewayTicketError::SignerFailed)?;
        Self::parse(&format!("{input}.{}", URL_SAFE_NO_PAD.encode(signature)))
    }

    /// Return the exact ticket for transport. Never log this value.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Verify a ticket using only the caller's trusted issuer and dedicated keyring.
    ///
    /// The returned claims still require authorization and an atomic `(iss, jti)` replay claim.
    ///
    /// # Errors
    ///
    /// Rejects missing keys, wrong names or algorithms, malformed claims, invalid signatures,
    /// and tickets outside their exact 60-second validity window.
    pub fn verify(
        &self,
        trusted: &TrustedGatewayTicketKeys,
        now: u64,
    ) -> Result<VerifiedGatewayTicket, GatewayTicketError> {
        let (encoded_header, encoded_payload, encoded_signature) = split_compact(&self.0)?;
        let header = unique_object(&decode_segment(encoded_header)?)?;
        if header.get("alg").and_then(Value::as_str) != Some("Ed25519")
            || header.get("typ").and_then(Value::as_str) != Some("spl-gw-ticket+jwt")
            || ["jwk", "jku", "x5u", "x5c", "crit", "b64"]
                .into_iter()
                .any(|field| header.contains_key(field))
        {
            return Err(GatewayTicketError::InvalidTicket);
        }
        let kid =
            header.get("kid").and_then(Value::as_str).ok_or(GatewayTicketError::InvalidTicket)?;
        if !valid_kid(kid) {
            return Err(GatewayTicketError::InvalidTicket);
        }
        let key = trusted.keys.get(kid).ok_or(GatewayTicketError::InvalidTicket)?;
        let signature = decode_segment(encoded_signature)?;
        if signature.len() != 64 {
            return Err(GatewayTicketError::InvalidTicket);
        }
        let input = format!("{encoded_header}.{encoded_payload}");
        ed25519_verify(key, input.as_bytes(), &signature)
            .map_err(|_| GatewayTicketError::InvalidTicket)?;
        let payload = unique_object(&decode_segment(encoded_payload)?)?;
        let cnf = payload
            .get("cnf")
            .and_then(Value::as_object)
            .ok_or(GatewayTicketError::InvalidTicket)?;
        let claims = GatewayTicketClaims {
            iss: text(&payload, "iss")?.to_owned(),
            jti: identifier(&payload, "jti")?,
            sub: identifier(&payload, "sub")?,
            did: identifier(&payload, "did")?,
            org: identifier(&payload, "org")?,
            host: identifier(&payload, "host")?,
            gateway_network: identifier(&payload, "gateway_network")?,
            remote_user: text(&payload, "remote_user")?.to_owned(),
            ssh_key_sha256: text(&payload, "ssh_key_sha256")?.to_owned(),
            cnf_jkt: text(cnf, "jkt")?.to_owned(),
            iat: payload
                .get("iat")
                .and_then(Value::as_u64)
                .ok_or(GatewayTicketError::InvalidTicket)?,
            exp: payload
                .get("exp")
                .and_then(Value::as_u64)
                .ok_or(GatewayTicketError::InvalidTicket)?,
        };
        if payload.get("aud").and_then(Value::as_str) != Some("spl-gw/1")
            || claims.iss != trusted.issuer
            || claims.validate().is_err()
            || now < claims.iat
            || now >= claims.exp
        {
            return Err(GatewayTicketError::InvalidTicket);
        }
        Ok(VerifiedGatewayTicket { expires_at: claims.exp, claims })
    }
}

/// A configured deployment issuer and dedicated ticket-signing public keys.
pub struct TrustedGatewayTicketKeys {
    issuer: String,
    keys: BTreeMap<String, [u8; 32]>,
}

impl fmt::Debug for TrustedGatewayTicketKeys {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("TrustedGatewayTicketKeys([CONFIGURED])")
    }
}

impl TrustedGatewayTicketKeys {
    /// Create an empty ticket-only keyring for one canonical trusted HTTPS issuer.
    ///
    /// # Errors
    ///
    /// Rejects a noncanonical origin.
    pub fn new(issuer: impl Into<String>) -> Result<Self, GatewayTicketError> {
        let issuer = issuer.into();
        validate_origin(&issuer).map_err(|_| GatewayTicketError::InvalidContext)?;
        Ok(Self { issuer, keys: BTreeMap::new() })
    }

    /// Add one configured public key for a bounded key identifier.
    ///
    /// # Errors
    ///
    /// Rejects malformed or duplicate identifiers and invalid Ed25519 public keys.
    pub fn insert(&mut self, kid: &str, public_key: &[u8]) -> Result<(), GatewayTicketError> {
        if !valid_kid(kid) || self.keys.contains_key(kid) {
            return Err(GatewayTicketError::InvalidContext);
        }
        let key: [u8; 32] =
            public_key.try_into().map_err(|_| GatewayTicketError::InvalidContext)?;
        ed25519_dalek::VerifyingKey::from_bytes(&key)
            .map_err(|_| GatewayTicketError::InvalidContext)?;
        self.keys.insert(kid.to_owned(), key);
        Ok(())
    }
}

/// Signature and claim evidence only. Replay, policy, and SSH-key use remain consumer checks.
pub struct VerifiedGatewayTicket {
    claims: GatewayTicketClaims,
    expires_at: u64,
}

impl fmt::Debug for VerifiedGatewayTicket {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("VerifiedGatewayTicket([STATELESS; REPLAY NOT CLAIMED])")
    }
}

impl VerifiedGatewayTicket {
    #[must_use]
    pub fn claims(&self) -> &GatewayTicketClaims {
        &self.claims
    }

    #[must_use]
    pub const fn expires_at(&self) -> u64 {
        self.expires_at
    }
}

/// Hash bytes already decoded from a canonical raw SSH public key.
///
/// This only computes SHA-256; callers must validate SSH syntax and private-key possession.
#[must_use]
pub fn gateway_ssh_key_sha256(raw_blob: &[u8]) -> String {
    URL_SAFE_NO_PAD.encode(Sha256::digest(raw_blob))
}

fn split_compact(value: &str) -> Result<(&str, &str, &str), GatewayTicketError> {
    if value.is_empty() || value.len() > MAX_GATEWAY_TICKET_BYTES || !value.is_ascii() {
        return Err(GatewayTicketError::InvalidTicket);
    }
    let mut parts = value.split('.');
    let segments = (
        parts.next().ok_or(GatewayTicketError::InvalidTicket)?,
        parts.next().ok_or(GatewayTicketError::InvalidTicket)?,
        parts.next().ok_or(GatewayTicketError::InvalidTicket)?,
    );
    if parts.next().is_some()
        || [segments.0, segments.1, segments.2].into_iter().any(|part| {
            part.is_empty()
                || !part.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
        })
    {
        return Err(GatewayTicketError::InvalidTicket);
    }
    Ok(segments)
}

fn decode_segment(value: &str) -> Result<Vec<u8>, GatewayTicketError> {
    dpop::decode_segment(value).map_err(|_| GatewayTicketError::InvalidTicket)
}

fn fixed_hash(value: &str) -> Result<[u8; 32], GatewayTicketError> {
    dpop::decode_fixed_32(value).map_err(|_| GatewayTicketError::InvalidTicket)
}

fn unique_object(bytes: &[u8]) -> Result<serde_json::Map<String, Value>, GatewayTicketError> {
    dpop::parse_unique_json(bytes)
        .map_err(|_| GatewayTicketError::InvalidTicket)?
        .as_object()
        .cloned()
        .ok_or(GatewayTicketError::InvalidTicket)
}

fn text<'a>(
    object: &'a serde_json::Map<String, Value>,
    key: &str,
) -> Result<&'a str, GatewayTicketError> {
    object.get(key).and_then(Value::as_str).ok_or(GatewayTicketError::InvalidTicket)
}

fn identifier(
    object: &serde_json::Map<String, Value>,
    key: &str,
) -> Result<Uuid, GatewayTicketError> {
    let value = text(object, key)?;
    let id = Uuid::parse_str(value).map_err(|_| GatewayTicketError::InvalidTicket)?;
    if id.to_string() != value || validate_uuid_v7(id).is_err() {
        return Err(GatewayTicketError::InvalidTicket);
    }
    Ok(id)
}

fn valid_kid(kid: &str) -> bool {
    !kid.is_empty()
        && kid.len() <= MAX_KID_BYTES
        && kid.bytes().all(|byte| byte.is_ascii_alphanumeric() || b"-_.".contains(&byte))
}
